await seguir(c, 1500);
out.final = await pantalla(c);
await m('9-recibido');
out.recibido = await c.ev('document.getElementById("pfPantalla").innerText.replace(/\\n+/g," / ") + " || " + document.getElementById("pfPie").innerText.replace(/\\n+/g," / ")');
out.avisoFinal = (await avisos(c)).map(a => [a.estado_curacion, a.operacion, a.moneda, a.precio, a.plazo, a.disponible_desde, (a.caracteristicas||[]).join('+'), a.fotos.length, a.amoblado].join(' | '));
out.eventos = await c.ev('JSON.parse(localStorage.getItem("bp_eventos")||"[]").map(e=>e.evento).join(",")');
out.errores = c.errores; out.consola = c.consola;
console.log(JSON.stringify(out, null, 1)); await c.cerrar(); process.exit(0);
